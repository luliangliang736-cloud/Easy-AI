export function translateCanvasText(text, language) {
  if (language !== "en") return text;
  const value = String(text ?? "");
  if (!value) return value;
  if (Object.prototype.hasOwnProperty.call(EXACT, value)) return EXACT[value];
  for (const [pattern, build] of PATTERNS) {
    const match = value.match(pattern);
    if (match) return build(match);
  }
  return value;
}

/** 专业创作模式的翻译 hook：t() 按当前语言翻译中文界面文案。 */
export function useCanvasT() {
  const { language, toggleLanguage } = useAppLanguage();
  const t = useMemo(
    () => (text) => translateCanvasText(text, language),
    [language]
  );
  return { t, language, toggleLanguage };
}
